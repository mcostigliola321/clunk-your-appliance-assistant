interface EntryInput {
  id: string;
  kind?: ApplianceCatalogEntry["kind"];
  brand: BrandName;
  model: string;
  label: string;
  aliases: string[];
  verifiedProductCodes?: string[];
  productCodePrompt: string;
  loadStyle?: ApplianceCatalogEntry["loadStyle"];
  topology?: ApplianceCatalogEntry["topology"];
  checkProfile?: ApplianceCatalogEntry["checkProfile"];
  profile?: ApplianceCatalogEntry["profile"];
  modelUrl: string;
  troubleshootingSources: SourceReference[];
  exactPart?: RepairPackPart;
  capability?: CapabilityTier;
}

function entry(input: EntryInput): ApplianceCatalogEntry {
  const {
    modelUrl,
    exactPart,
    kind: _kind,
    profile: _profile,
    loadStyle,
    topology,
    checkProfile,
    verifiedProductCodes,
    capability,
    ...rest
  } = input;
  const kind = input.kind ?? "washer";
  const profile =
    input.profile ??
    (input.checkProfile === "filter-access" ? "washer-front-drain" : "washer-hose-only");
  const resolvedCapability =
    capability ??
    (exactPart
      ? isPurchaseReadyPart(exactPart)
        ? "purchase-ready"
        : "verified-part-unavailable"
      : "guided-checks");
  const resolvedProductCodes = verifiedProductCodes ?? [];
  return {
    ...rest,
    kind,
    profile,
    symptomCoverage: buildSymptomCoverage({
      modelId: input.id,
      kind,
      capability: resolvedCapability,
      troubleshootingSources: input.troubleshootingSources,
      ...(exactPart ? { exactPart } : {}),
      verifiedProductCodes: resolvedProductCodes,
    }),
    ...(kind === "washer" ? { loadStyle: loadStyle ?? "front-load" } : {}),
    ...(topology ? { topology } : {}),
    ...(checkProfile ? { checkProfile } : {}),
    verifiedProductCodes: resolvedProductCodes,
    modelSource: source(
      `${input.id}-model`,
      "manufacturer-model",
      `${input.brand} ${input.model} official support`,
      modelUrl,
      input.brand,
      input.model,
    ),
  };
}

